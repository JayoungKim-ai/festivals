/** 시도 이름 줄임 (지역 버튼·태그를 짧게) */
const SIDO_SHORT = {
  서울특별시: '서울',
  부산광역시: '부산',
  대구광역시: '대구',
  인천광역시: '인천',
  광주광역시: '광주',
  대전광역시: '대전',
  울산광역시: '울산',
  세종특별자치시: '세종',
  경기도: '경기',
  강원도: '강원',
  강원특별자치도: '강원',
  충청북도: '충북',
  충청남도: '충남',
  전라북도: '전북',
  전북특별자치도: '전북',
  전라남도: '전남',
  전남광주통합특별시: '전남광주',
  경상북도: '경북',
  경상남도: '경남',
  제주특별자치도: '제주',
}

/** "충청북도" → "충북" (목록에 없으면 원래 이름) */
export function shortRegionName(name) {
  return SIDO_SHORT[name] || name
}

/** 선택한 지역 목록을 문구로 (예: ["서울특별시","부산광역시"] → "서울·부산") */
export function formatRegionList(regions) {
  return regions.map(shortRegionName).join('·')
}
